#Requires -Version 5.1
<#
.SYNOPSIS
    Distill global memory + per-framework rules into framework-specific files.

.DESCRIPTION
    Reads:
      - agent-memory/01_globel.md                (global memory, always loaded into AI)
      - agent-memory/03_agents/<name>.md         (per-framework rules)

    Writes:
      - agent-memory/04_distilled/<name>.md      (combined, default; UTF-8 NO BOM)
      - Optional: $HOME/<framework-specific-path>/<rules-file>   (-Apply -Confirm)

    v2 default: write only to agent-memory/04_distilled/<name>.md. To push into actual
    framework config dirs, use -Apply with -Confirm.

.PARAMETER RepoRoot
    Path to the central toolkit repo. Defaults to the script's directory.

.PARAMETER Apply
    Actually write to each framework's rules location. Default is FALSE (dry-run).
    Use -Apply -Confirm to proceed.

.PARAMETER List
    Just print available frameworks and exit.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\distill-memory.ps1
    powershell -ExecutionPolicy Bypass -File .\distill-memory.ps1 -Apply -Confirm
    powershell -ExecutionPolicy Bypass -File .\distill-memory.ps1 -List

.NOTES
    Encoding: All reads/writes are UTF-8 NO BOM. Windows PS 5.1 Get-Content / Set-Content
    default to system code page (GBK on Chinese Windows) which corrupts Chinese text.
    This script uses [System.IO.File]::ReadAllText/WriteAllText with explicit UTF-8.

    Framework-specific rules locations (v2, 2026-07-09 verified):
      - Claude Code:   $HOME/.claude/CLAUDE.md               (global, auto-loaded)
      - OpenAI Codex:  $HOME/.codex/AGENTS.md                (global, auto-loaded)
      - Gemini CLI:    $HOME/.gemini/GEMINI.md               (global, auto-loaded, v0.47.0+)
      - CodeWhale:     $HOME/.codewhale/instructions.md      (autogenerated — DO NOT overwrite)
      - Mimo:          (no standard global rules location; skipped)
      - Copilot CLI:   (no standard global rules location; skipped)
      - Qoder:         (no standard global rules location; skipped)
      - MoltBot:       (no skill system; skipped)

    Memory workflow (weekly, or on user request):
      1. New raw memory → drop in agent-memory/00_inbox/<framework>-<topic>.md
      2. AI distills (manual or scheduled): moves relevant pieces to:
         - 01_globel.md                                   (global, concise)
         - 02_topics/<topic>.md                           (long topical, on-demand)
         - 03_agents/<x>.md                               (framework-specific)
      3. Human review: AI shows raw + distilled side-by-side, user confirms
      4. Run distill-memory.ps1 → 04_distilled/<x>.md
      5. Optional: distill-memory.ps1 -Apply -Confirm → push to framework config

    Backlog (v3, 2026-07-14 added):
      - 05_backlog/ 目录存 in-flight 下批需求（不进 distill，默认 -SkipBacklog:$true）
      - 显式 -SkipBacklog:$false 强制包含（基本不会用，留给 debug）
#>

[CmdletBinding()]
param(
    [switch]$Apply,
    [switch]$Confirm,
    [switch]$List,
    [switch]$SkipBacklog = $true,
    [string]$RepoRoot
)

# --- bootstrap ---------------------------------------------------------------

if ([string]::IsNullOrWhiteSpace($RepoRoot)) {
    if ($PSScriptRoot) { $RepoRoot = $PSScriptRoot }
    elseif ($MyInvocation.MyCommand.Path) { $RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path }
    else { $RepoRoot = (Get-Location).Path }
}

$Repo = (Resolve-Path -LiteralPath $RepoRoot).Path
$MemoryRoot    = Join-Path $Repo 'agent-memory'
$GlobelPath    = Join-Path $MemoryRoot '01_globel.md'
$AgentsDir     = Join-Path $MemoryRoot '03_agents'
$DistilledDir  = Join-Path $MemoryRoot '04_distilled'

# Explicit UTF-8 NO BOM (avoid system code page / BOM issues on Windows PS 5.1)
$Utf8NoBom = New-Object System.Text.UTF8Encoding($False)

if (-not (Test-Path -LiteralPath $MemoryRoot)) {
    Write-Error "agent-memory/ not found at $MemoryRoot"
    exit 1
}
if (-not (Test-Path -LiteralPath $GlobelPath)) {
    Write-Error "01_globel.md not found at $GlobelPath"
    exit 1
}

# Framework -> rules file path mapping (only frameworks with a known global rules location)
# NOTE: CodeWhale instructions.md is autogenerated by runtime — NOT mapped here
# NOTE: MoltBot v0.1.0 has no skill system — NOT mapped here
$frameworkMap = @{
    'claude'    = @{ path = (Join-Path $HOME '.claude\CLAUDE.md');   label = 'Claude Code' }
    'codex'     = @{ path = (Join-Path $HOME '.codex\AGENTS.md');     label = 'OpenAI Codex' }
    'gemini'    = @{ path = (Join-Path $HOME '.gemini\GEMINI.md');    label = 'Google Gemini CLI' }
}

# --- list mode ---------------------------------------------------------------

if ($List) {
    Write-Host "=== source ==="
    Write-Host "  01_globel.md  (global memory)"
    Write-Host ""
    Write-Host "=== 03_agents/ ==="
    Get-ChildItem -LiteralPath $AgentsDir -Filter '*.md' -ErrorAction SilentlyContinue | ForEach-Object {
        $base = [System.IO.Path]::GetFileNameWithoutExtension($_.Name)
        $info = $frameworkMap[$base]
        $marker = if ($info) { '[writable]' } else { '[distill-only]' }
        Write-Host ("  {0,-10} {1,-22} {2}" -f $base, $info.label, $marker)
    }
    Write-Host ""
    Write-Host "=== 05_backlog/ ==="
    $BacklogDir = Join-Path $MemoryRoot '05_backlog'
    if (Test-Path -LiteralPath $BacklogDir) {
        Get-ChildItem -LiteralPath $BacklogDir -Filter '*.md' -ErrorAction SilentlyContinue | ForEach-Object {
            $base = [System.IO.Path]::GetFileNameWithoutExtension($_.Name)
            $marker = if ($SkipBacklog) { '[skipped by -SkipBacklog]' } else { '[included]' }
            Write-Host ("  {0,-40} {1}" -f $base, $marker)
        }
    } else {
        Write-Host "  (directory not present)"
    }
    exit 0
}

# --- helpers -----------------------------------------------------------------

function Read-Utf8([string]$Path) {
    return [System.IO.File]::ReadAllText($Path, $Utf8NoBom)
}

function Write-Utf8([string]$Path, [string]$Content) {
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        $null = New-Item -ItemType Directory -Path $dir -Force
    }
    [System.IO.File]::WriteAllText($Path, $Content, $Utf8NoBom)
}

# --- ensure 04_distilled/ exists ---------------------------------------------

$null = New-Item -ItemType Directory -Path $DistilledDir -Force

# --- read global memory ------------------------------------------------------

$globelContent = Read-Utf8 $GlobelPath

# --- main loop over agents ---------------------------------------------------

$wroteDistilled = 0
$wroteFramework = 0
$skippedBacklog = 0

# Build skip set from 05_backlog/ if -SkipBacklog is set
$backlogNames = @()
if ($SkipBacklog) {
    $BacklogDir = Join-Path $MemoryRoot '05_backlog'
    if (Test-Path -LiteralPath $BacklogDir) {
        $backlogNames = @(Get-ChildItem -LiteralPath $BacklogDir -Filter '*.md' -ErrorAction SilentlyContinue |
            ForEach-Object { [System.IO.Path]::GetFileNameWithoutExtension($_.Name) })
    }
}

Get-ChildItem -LiteralPath $AgentsDir -Filter '*.md' -ErrorAction SilentlyContinue | ForEach-Object {
    $name = [System.IO.Path]::GetFileNameWithoutExtension($_.Name)

    if ($SkipBacklog -and ($backlogNames -contains $name)) {
        $skippedBacklog++
        Write-Host "[backlog-skip] $name (in 05_backlog/, -SkipBacklog default)"
        return
    }

    $agentContent = Read-Utf8 $_.FullName

    $combined = @"
# Distilled rules for: $name
# Source: agent-memory/01_globel.md + agent-memory/03_agents/$name.md
# Generated: $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')
# DO NOT edit this file directly -- edit the source files and re-run distill-memory.ps1

# === 01_globel.md (global memory) ===

$globelContent

# === 03_agents/$name.md ===

$agentContent
"@

    # Always write to agent-memory/04_distilled/<name>.md
    $dstDistilled = Join-Path $DistilledDir "$name.md"
    Write-Utf8 $dstDistilled $combined
    $wroteDistilled++
    Write-Host "[distilled] $name -> $dstDistilled"

    # Optionally write to framework's real rules location
    $info = $frameworkMap[$name]
    if ($Apply -and $info) {
        if (-not $Confirm) {
            Write-Warning "Use -Apply -Confirm to actually write to $($info.path). Skipped."
            return
        }
        $dstFramework = $info.path
        Write-Utf8 $dstFramework $combined
        $wroteFramework++
        Write-Host "[applied]  $name -> $dstFramework"
    }
}

Write-Host ""
Write-Host "=== distill-memory.ps1 summary ==="
Write-Host "  distilled: $wroteDistilled file(s) in agent-memory/04_distilled/"
if ($SkipBacklog -and $skippedBacklog -gt 0) {
    Write-Host "  backlog-skipped: $skippedBacklog file(s) from 05_backlog/ (use -SkipBacklog:`$false to include)"
}
if ($Apply) {
    Write-Host "  applied:   $wroteFramework file(s) to framework rules locations"
    if (-not $Confirm) {
        Write-Host "  (apply was requested but -Confirm not set; no writes to framework dirs)"
    }
} else {
    Write-Host "  applied:   0 (use -Apply -Confirm to also write to framework rules locations)"
}